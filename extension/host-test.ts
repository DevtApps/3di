import * as vscode from 'vscode';
import * as assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

export async function run() {
  const results: Record<string, unknown> = {};
  const extension = vscode.extensions.getExtension('3di-local.3di-engine');
  assert.ok(extension, 'Extensão não encontrada no Extension Host');
  const api = await extension.activate();
  const doc = await vscode.workspace.openTextDocument({ language: '3di', content: 'show(sphere(0.5).color("red").name("bola"))' });
  await vscode.window.showTextDocument(doc);
  await vscode.commands.executeCommand('3di.openPreview');
  const shot = await api.host.preview('screenshot', { view: 'grid' });
  const bytes = Buffer.from(shot.png, 'base64');
  assert.equal(bytes.subarray(1, 4).toString(), 'PNG');
  assert.ok(bytes.length > 2000, `PNG vazio: ${bytes.length} bytes`);
  results.previewBytes = bytes.length;
  if (process.env.THREEDI_TEST_SCREENSHOT) await writeFile(process.env.THREEDI_TEST_SCREENSHOT, bytes);
  const edit = new vscode.WorkspaceEdit();
  edit.replace(doc.uri, new vscode.Range(0, 0, doc.lineCount, 0), 'show(no_such_shape())');
  await vscode.workspace.applyEdit(edit);
  const deadline = Date.now() + 10000;
  while (!vscode.languages.getDiagnostics(doc.uri).length && Date.now() < deadline) await new Promise((r) => setTimeout(r, 50));
  assert.ok(vscode.languages.getDiagnostics(doc.uri).some((d) => d.source === '3DI'));
  results.diagnostics = true;
  await api.host.setScript('show(box(1).color("blue"))');
  assert.equal(doc.getText(), 'show(box(1).color("blue"))');
  assert.equal(vscode.languages.getDiagnostics(doc.uri).length, 0);
  results.edit = true;
  await vscode.commands.executeCommand('3di.previewOnly');
  assert.equal(await api.host.getScript(), doc.getText());
  await vscode.commands.executeCommand('3di.showCode');
  assert.equal(vscode.window.activeTextEditor?.document.uri.toString(), doc.uri.toString());
  results.previewOnly = true;
  const completions = await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider', doc.uri, new vscode.Position(0, 0));
  assert.ok(completions?.items.some((item) => item.label === 'sphere'));
  results.completion = true;
  const glb = await api.engine.run({ code: doc.getText(), task: 'export', res: 16 });
  assert.equal(Buffer.from(glb.glb).subarray(0, 4).toString(), 'glTF');
  results.glb = glb.glb.length;
  const mcpDeadline = Date.now() + 10000;
  while (!api.endpoint() && Date.now() < mcpDeadline) await new Promise((r) => setTimeout(r, 50));
  assert.ok(api.endpoint(), 'MCP não iniciou no Extension Host');
  const client = new Client({ name: 'extension-host-test', version: '1.0.0' }, { capabilities: {} });
  await client.connect(new StreamableHTTPClientTransport(new URL(api.endpoint())));
  try {
    const script = await client.callTool({ name: 'get_script' });
    assert.equal((script.content as any[])[0].text, doc.getText());
    const image = await client.callTool({ name: 'screenshot', arguments: { view: 'front' } });
    assert.equal((image.content as any[])[0].type, 'image');
    results.mcp = true;
  } finally { await client.close(); }
  const commands = await vscode.commands.getCommands();
  assert.ok(commands.includes('3di.newProject'));
  results.newProjectCommand = true;
  if (process.env.THREEDI_TEST_RESULT) await writeFile(process.env.THREEDI_TEST_RESULT, JSON.stringify(results, null, 2));
  console.log('3DI_EXTENSION_TEST_OK', JSON.stringify(results));
}
